"""Build the self-hosted IBM Plex Sans Arabic subsets in web/assets/fonts/.

The font is fetched from the google/fonts repository at build time and subset here,
so the published page loads the face from its own origin. No CDN at runtime is the
whole point: it is what makes "this page sends nothing anywhere" checkable.
"""

import pathlib
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont

SOURCE = (
    "https://raw.githubusercontent.com/google/fonts/main/ofl/ibmplexsansarabic/"
    "IBMPlexSansArabic-{name}.ttf"
)
# Only the weights the design uses. Thin through Light would be 3 more files for
# nothing, since no rule in app.css asks for them.
WEIGHTS = {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700}
# Basic Latin and Latin-1 carry the source names (Stremio, PenguPlay, Netflix), the
# digits, and the guillemets the Arabic prose uses for «quoted» terms. U+0600-06FF is
# standard Arabic plus its comma, question mark, and Arabic-Indic digits. General
# Punctuation carries the quotes, the ellipsis, and the en dash. Arabic Supplement and
# Extended-A are dropped on purpose: they cover languages this page does not write.
KEEP = (
    (0x0000, 0x00FF),
    (0x0600, 0x06FF),
    (0x2000, 0x206F),
)
OUT = pathlib.Path("web/assets/fonts")
CACHE = OUT / ".source"


def codepoints():
    points = []
    for start, end in KEEP:
        points.extend(range(start, end + 1))
    return points


def fetch(name):
    CACHE.mkdir(parents=True, exist_ok=True)
    target = CACHE / f"{name}.ttf"
    if not target.exists():
        request = urllib.request.Request(SOURCE.format(name=name))
        with urllib.request.urlopen(request, timeout=120) as response:
            target.write_bytes(response.read())
    return target


def build(source, weight):
    font = TTFont(source)
    options = subset.Options()
    options.flavor = "woff2"
    # Arabic shaping lives in these features. Dropping them produces disconnected
    # letters, which is not a size trade-off worth making.
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.notdef_outline = True
    # Chrome, Firefox, and Android all rasterize unhinted text now, so the hinting
    # tables are download weight with no rendering effect to show for it.
    options.hinting = False
    options.drop_tables = list(options.drop_tables) + ["meta"]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints())
    subsetter.subset(font)
    target = OUT / f"plex-arabic-{weight}.woff2"
    font.flavor = "woff2"
    font.save(target)
    return target


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rules = []
    total = 0
    for name, weight in WEIGHTS.items():
        source = fetch(name)
        target = build(source, weight)
        size = target.stat().st_size
        total += size
        print(f"  {weight}  {size:>7,} bytes  {target.name}")
        rules.append(
            "@font-face {\n"
            "  font-family: 'IBM Plex Sans Arabic';\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('{target.name}') format('woff2');\n"
            "}"
        )

    sheet = OUT / "plex.css"
    sheet.write_text(
        "/* Generated by tools/make-fonts.py. Edit the tool, not this file. */\n\n"
        + "\n\n".join(rules)
        + "\n",
        encoding="utf-8",
    )
    print(f"  total font payload: {total:,} bytes")
    print(f"  subset of {len(codepoints()):,} codepoints per weight")


if __name__ == "__main__":
    main()
